#!/usr/bin/env node
// Copies the shared nouzl_mobile packages into packages/ and writes a hash
// manifest (spec 0001, Sync contract). The copies are read only here: change
// shared code in nouzl_mobile, commit it there, then run this again.
//
// Usage: node scripts/sync-mobile-packages.mjs [path to nouzl_mobile]
// Default source: ../nouzl_mobile next to this repo.
//
// Refuses to sync when the source packages have uncommitted changes (the
// manifest would name a commit that does not hold them) or carry the
// global.i= malware marker.

import { execFileSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { MALWARE_MARKER, MANIFEST_NAME, SYNCED_PACKAGES, listFiles, sha256 } from './synced-packages.mjs';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = resolve(process.argv[2] ?? join(repoRoot, '..', 'nouzl_mobile'));

function git(...args) {
  return execFileSync('git', ['-C', source, ...args], { encoding: 'utf8' }).trim();
}

function fail(message) {
  console.error(`sync-mobile-packages: ${message}`);
  process.exit(1);
}

if (!existsSync(join(source, 'packages'))) fail(`no packages/ folder in ${source}`);

const sourcePaths = SYNCED_PACKAGES.map((name) => `packages/${name}`);
const dirty = git('status', '--porcelain', '--', ...sourcePaths);
if (dirty) fail(`uncommitted changes in nouzl_mobile, commit them there first:\n${dirty}`);
const commit = git('rev-parse', 'HEAD');

const files = [];
for (const name of SYNCED_PACKAGES) {
  const from = join(source, 'packages', name);
  if (!existsSync(from)) fail(`nouzl_mobile has no packages/${name}`);
  for (const rel of listFiles(from)) {
    const buffer = readFileSync(join(from, rel));
    if (buffer.toString('utf8').includes(MALWARE_MARKER))
      fail(`packages/${name}/${rel} contains ${MALWARE_MARKER}; do not sync, investigate.`);
    files.push({ path: `${name}/${rel}`, sha256: sha256(buffer) });
  }
}

const target = join(repoRoot, 'packages');
for (const name of SYNCED_PACKAGES) rmSync(join(target, name), { recursive: true, force: true });
for (const { path } of files) {
  const to = join(target, ...path.split('/'));
  mkdirSync(dirname(to), { recursive: true });
  copyFileSync(join(source, 'packages', ...path.split('/')), to);
}

const manifest = {
  note: 'Generated by scripts/sync-mobile-packages.mjs. Do not edit the listed packages here; change them in nouzl_mobile and sync again.',
  source: 'nouzl_mobile',
  commit,
  syncedAt: new Date().toISOString(),
  packages: SYNCED_PACKAGES,
  files,
};
writeFileSync(join(target, MANIFEST_NAME), JSON.stringify(manifest, null, 2) + '\n');
console.log(
  `sync-mobile-packages: copied ${files.length} files from nouzl_mobile@${commit.slice(0, 7)} into packages/`,
);
